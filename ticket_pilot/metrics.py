"""Local performance report over pipeline records and completed execution summaries."""
from __future__ import annotations

import re
import time
from collections import defaultdict
from datetime import datetime, timedelta, timezone
from statistics import mean, median

from .core import meta_get
from .metrics_usage import timestamp

UTC = timezone.utc
WEEKS = 12
DEFAULT_DAYS = 14
MAX_DAYS = 90
INTERVENTIONS = ("ws_set_blocked", "reply", "unblock", "review_override", "check_override", "manual_rework")
MERGE_TARGETS = ("milestone", "staging", "main", "other")


def iso(at):
    return datetime.fromtimestamp(at, UTC).isoformat()


def create_marker(con, label):
    label = label.strip() if isinstance(label, str) else ""
    if not label or len(label) > 120 or not label.isprintable():
        raise SystemExit("시점 이름을 한 줄에 1~120자로 입력해 주세요")
    at = time.time()
    with con:
        key = con.execute("INSERT INTO metric_markers(at,label,kind) VALUES(?,?,'manual')", (at, label)).lastrowid
    return {"id": key, "at": iso(at), "label": label, "kind": "manual"}


def week_start(at):
    day = datetime.fromtimestamp(at, UTC).replace(hour=0, minute=0, second=0, microsecond=0)
    return day - timedelta(days=day.weekday())


def comparison_windows(at, days):
    width = timedelta(days=days).total_seconds()
    return (at - width, at), (at, at + width)


def _inside(at, start, end):
    return at is not None and start <= at < end


def _metric(value, n):
    return {"value": value, "n": n}


def _sample(values, reduce=mean):
    return _metric(round(reduce(values), 3) if values else None, len(values))


def _merge_target(base, repo, rules):
    if (base or "").startswith("milestone/"):
        return "milestone"
    config = rules.get(repo, {})
    if base and base in ("staging", (config.get("staging") or {}).get("branch")):
        return "staging"
    if base and base in ("main", "master", config.get("target"), (config.get("prod") or {}).get("branch")):
        return "main"
    return "other"


def _reported_block(comment):
    text = (comment or "").lower().removeprefix("blocked:").lstrip()
    # The history also contains questions generated by timeouts, checks, audits and the rework cap.
    return not (text.startswith(("규칙 위반", "tp 검사가 계속 실패", "ai 리뷰가"))
                or "without marking the pr ready; log " in text
                or re.match(r"\d+번 고친 뒤에도 tp 검사 실패", text))


def _records(con, rules):
    prs, production = [], {}
    for row in con.execute("""SELECT url,ticket_gid,repo,number,base,created_at,merged_at,prod_at
                              FROM prs WHERE merged_at IS NOT NULL OR prod_at IS NOT NULL"""):
        p = dict(row)
        for key in ("created_at", "merged_at", "prod_at"):
            p[key] = timestamp(p[key])
        p["target"] = _merge_target(p["base"], p["repo"], rules)
        prs.append(p)
        gid, at = p["ticket_gid"], p["prod_at"]
        if gid and at is not None and (gid not in production or at < production[gid]):
            production[gid] = at

    intervention = {}
    stability, caps = [], set()
    for row in con.execute(f"""SELECT kind,ts,ticket_gid,message FROM events
                               WHERE kind IN ({','.join('?' for _ in INTERVENTIONS)},'error',
                                 'conflict_rework','rework_cap')
                                 OR (kind IN ('agent_exit','agent_timeout') AND
                                    id NOT IN (SELECT exit_event FROM metric_agent_runs WHERE exit_event IS NOT NULL
                                               AND finished_at>0))""", INTERVENTIONS):
        at, kind, gid, message = timestamp(row["ts"]), row["kind"], row["ticket_gid"], row["message"] or ""
        if at is None:
            continue
        if kind in INTERVENTIONS:
            if gid and not (kind == "reply" and message.endswith("answer cleared")):
                intervention[gid] = min(at, intervention.get(gid, at))
        elif kind == "rework_cap":
            if match := re.search(r"PR #(\d+)", message):
                caps.add((gid, int(match[1]), at))
        else:
            stability.append((at, kind, message))
    # The old inbox keeps BLOCKED reports even after the workspace comment/status was overwritten.
    for row in con.execute("""SELECT ticket_gid,ts,body FROM notifications WHERE kind='blocked'
                              UNION ALL
                              SELECT r.ticket_gid,r.updated_at,r.ws_comment FROM runs r
                              LEFT JOIN metric_agent_runs a ON a.handle=r.terminal
                              WHERE r.ws_status='todo' AND upper(r.ws_comment) LIKE 'BLOCKED%'
                                AND a.has_ws_set IS NULL"""):
        at, gid = timestamp(row["ts"]), row["ticket_gid"]
        if gid and at is not None and _reported_block(row["body"]):
            intervention[gid] = min(at, intervention.get(gid, at))

    first_reviews, reviews = {}, []
    for row in con.execute("""SELECT r.pr_url,r.ticket_gid,r.created_at,r.verdict,r.rework_at,r.source,r.manual,p.number
                              FROM reviews r LEFT JOIN prs p ON p.url=r.pr_url ORDER BY r.id"""):
        at, rework = timestamp(row["created_at"]), timestamp(row["rework_at"])
        if row["source"] is None and not row["manual"] and at is not None:
            first_reviews.setdefault(row["pr_url"], (at, row["verdict"]))
        if rework is not None and any((row["ticket_gid"], row["number"], rework + offset) in caps for offset in (0, 1)):
            rework = None
        reviews.append((row["pr_url"], at, rework))

    usage = defaultdict(list)
    for row in con.execute("""SELECT ticket_gid,started_at,tool,tokens FROM metric_agent_runs WHERE kind='work'
                              UNION ALL
                              SELECT r.ticket_gid,r.started_at,a.tool,r.tokens FROM metric_review_tokens r
                              JOIN metric_agent_runs a ON a.log=r.log"""):
        usage[row["ticket_gid"]].append((row["started_at"], row["tool"], row["tokens"]))
    agents = con.execute("SELECT * FROM metric_agent_runs WHERE finished_at>0").fetchall()
    return prs, production, intervention, stability, first_reviews, reviews, usage, agents


def _period(records, start, end, observed_until):
    prs, production, intervention, stability, first_reviews, reviews, usage, agents = records
    observed_end = min(end, observed_until)
    cohort = {gid: at for gid, at in production.items() if _inside(at, start, observed_end)}
    no_intervention = sum(intervention.get(gid, float("inf")) > at for gid, at in cohort.items())
    ticket_tokens, sources = [], set()
    linked, measured = 0, 0
    for gid, at in cohort.items():
        runs = [(tool, tokens) for started, tool, tokens in usage.get(gid, ()) if started is None or started <= at]
        readable = [(tool, tokens) for tool, tokens in runs if tokens is not None]
        linked += len(runs)
        measured += len(readable)
        if readable:
            ticket_tokens.append(sum(tokens for _, tokens in readable))
            sources.update(tool for tool, _ in readable if tool)
    values = {
        "intervention_free": _metric(no_intervention / len(cohort) if cohort else None, len(cohort)),
        "tokens_per_ticket": _sample(ticket_tokens),
    }

    first = [verdict == "approve" for at, verdict in first_reviews.values() if _inside(at, start, observed_end)]
    rounds = defaultdict(int)
    for url, at, rework in reviews:
        if _inside(at, start, observed_end):
            rounds.setdefault(url, 0)
        if _inside(rework, start, observed_end):
            rounds[url] += 1
    values["first_review_approval"] = _sample(first)
    values["rework_rounds"] = _sample(list(rounds.values()))

    ready_times, production_times = defaultdict(list), defaultdict(list)
    for p in prs:
        created, merged, prod, target = p["created_at"], p["merged_at"], p["prod_at"], p["target"]
        if _inside(merged, start, observed_end) and created is not None and created <= merged:
            ready_times[target].append((merged - created) / 3600)
        if _inside(prod, start, observed_end) and merged is not None and merged <= prod:
            production_times[target].append((prod - merged) / 3600)
    for target in MERGE_TARGETS:
        values[f"pr_to_merge_{target}"] = _sample(ready_times[target], median)
        values[f"merge_to_prod_{target}"] = _sample(production_times[target], median)

    finished = [r for r in agents if _inside(r["finished_at"], start, observed_end)]
    readable_agents = [r for r in finished if r["tool_calls"] is not None]
    values["tools_per_run"] = _sample([r["tool_calls"] for r in readable_agents])
    for key in ("help_calls", "dev_calls", "wait_calls"):
        values[key] = _metric(sum(r[key] for r in readable_agents) if readable_agents else None, len(readable_agents))

    events = [(kind, message) for at, kind, message in stability if _inside(at, start, observed_end)]
    errors = {message for kind, message in events if kind == "error"}
    missing = sum(kind in ("agent_exit", "agent_timeout") for kind, _ in events)
    missing += sum(r["has_ws_set"] == 0 for r in finished)
    conflicts = sum(kind == "conflict_rework" for kind, _ in events)
    stability_metrics = (("errors", len(errors), sum(kind == "error" for kind, _ in events)),
                         ("missing_ws_set", missing, missing), ("conflict_rework", conflicts, conflicts))
    for key, count, samples in stability_metrics:
        values[key] = _metric(count if start < observed_end else None, samples)
    return {"start": iso(start), "end": iso(end), "observed_until": iso(observed_end) if start < observed_end else None,
            "values": values, "token_sources": sorted(sources), "token_runs": measured, "linked_runs": linked,
            "execution_count": len(finished)}


def report(con, *, mark_id=None, days=DEFAULT_DAYS, at=None, rules=None):
    if type(days) is not int or not 1 <= days <= MAX_DAYS:
        raise ValueError(f"비교 기간은 1~{MAX_DAYS}일로 입력해 주세요")
    at = time.time() if at is None else at
    monday = week_start(at)
    start = monday - timedelta(weeks=WEEKS - 1)
    markers = [dict(row) for row in con.execute("SELECT * FROM metric_markers ORDER BY at DESC,id DESC")]
    marker = next((row for row in markers if row["id"] == mark_id), None)
    if mark_id is not None and marker is None:
        raise ValueError("시점을 찾을 수 없어요")
    records = _records(con, rules or {})
    weeks = [(start + timedelta(weeks=i)).timestamp() for i in range(WEEKS + 1)]
    comparison = None
    if marker:
        before, after = comparison_windows(marker["at"], days)
        complete = at >= after[1]
        if not complete:
            # Compare the same elapsed time on both sides while the requested after window fills.
            elapsed = max(0, at - after[0])
            before = (before[1] - elapsed, before[1])
            after = (after[0], after[0] + elapsed)
        comparison = {"before": _period(records, *before, at), "after": _period(records, *after, at), "complete": complete}
    return {
        "period": _period(records, weeks[0], at, at),
        "weeks": [_period(records, lo, hi, at) for lo, hi in zip(weeks, weeks[1:])],
        "markers": [row | {"at": iso(row["at"])} for row in markers],
        "comparison": comparison,
        "pending": con.execute("SELECT count(*) FROM metric_agent_runs WHERE finished_at IS NULL").fetchone()[0],
        "initialized": bool(meta_get(con, "metrics_history_discovered")),
    }
